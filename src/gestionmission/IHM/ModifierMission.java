    private void jComboBoxListMissionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jComboBoxListMissionActionPerformed
        if (chargementEnCours) {
            return;
        }
        remplirChamps((Mission) jComboBoxListMission.getSelectedItem());
    }//GEN-LAST:event_jComboBoxListMissionActionPerformed

    /**
     * Pré-remplit les champs avec la mission choisie (ou les vide si null)
     */
    private void remplirChamps(Mission m) {
        uneMissionSelected = m;   // on remplit l'attribut, pas une variable locale
        if (m == null) {
            jTextFieldTitre.setText("");
            jTextFieldDescription.setText("");
            jTextFieldDateDebut.setText("");
            jTextFieldDateFin.setText("");
            jTextFieldBudget.setText("");
            return;
        }
        jTextFieldTitre.setText(m.getTitre());
        jTextFieldDescription.setText(m.getDescription());
        jTextFieldDateDebut.setText(m.getDateDebut() != null ? String.valueOf(m.getDateDebut()) : "");
        jTextFieldDateFin.setText(m.getDateFin() != null ? String.valueOf(m.getDateFin()) : "");
        jComboBoxStatut.setSelectedItem(m.getStatut());
        jComboBoxPriorite.setSelectedItem(m.getPriorite());
        jTextFieldBudget.setText(String.valueOf(m.getBudget()));
    }

    /**
     * Charge la liste des missions depuis la base dans la combo
     */
    public void iniComboBox(){
        chargementEnCours = true;
        try {
            MissionDAO uneMissionDAO = new MissionDAO();
            jComboBoxListMission.removeAllItems();
            lesMissions = uneMissionDAO.lister();
            for (Mission m : lesMissions) {
                jComboBoxListMission.addItem(m);
            }
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Impossible de charger les missions : " + ex.getMessage(),
                    "Erreur", JOptionPane.ERROR_MESSAGE);
        } finally {
            chargementEnCours = false;
        }
        // Affiche la première mission de la liste
        remplirChamps((Mission) jComboBoxListMission.getSelectedItem());
    }

    /**
     * Après un rechargement, re-sélectionne la mission qu'on vient de modifier
     */
    private void reselectionner(int id) {
        for (int i = 0; i < jComboBoxListMission.getItemCount(); i++) {
            if (jComboBoxListMission.getItemAt(i).getId() == id) {
                jComboBoxListMission.setSelectedIndex(i);  // déclenche remplirChamps
                return;
            }
        }
    }
    
    /**
     * Affiche seulement "id - titre" dans la liste des missions,
     * sans dépendre du toString() de Mission.
     */
    private void initAffichageListeMissions() {
        jComboBoxListMission.setRenderer(new javax.swing.DefaultListCellRenderer() {
            @Override
            public java.awt.Component getListCellRendererComponent(javax.swing.JList<?> list, Object value,
                    int index, boolean isSelected, boolean cellHasFocus) {
                super.getListCellRendererComponent(list, value, index, isSelected, cellHasFocus);
                if (value instanceof Mission) {
                    Mission m = (Mission) value;
                    setText(m.getId() + " - " + m.getTitre());
                } else {
                    setText("");
                }
                return this;
            }
        });
    }

    private void initComboBox(){
        for (Statut statut : Statut.values()) {
            jComboBoxStatut.addItem(statut);
        }
        for (Priorite priorite : Priorite.values()){
            jComboBoxPriorite.addItem(priorite); 
        }
    }
    
