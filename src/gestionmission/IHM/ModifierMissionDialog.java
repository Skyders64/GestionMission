    private void jButtonValiderActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonValiderActionPerformed
        if (mission == null) {
            return;
        }

        String titre = jTextFieldTitre.getText().trim();
        if (titre.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Le titre est obligatoire.", "Erreur", JOptionPane.ERROR_MESSAGE);
            return;
        }

        LocalDate dateDebut;
        LocalDate dateFin;
        try {
            dateDebut = LocalDate.parse(jTextFieldDateDebut.getText().trim());
            dateFin = LocalDate.parse(jTextFieldDateFin.getText().trim());
        } catch (DateTimeParseException e) {
            JOptionPane.showMessageDialog(this, "Les dates doivent être au format AAAA-MM-JJ (ex : 2026-10-12).",
                    "Erreur", JOptionPane.ERROR_MESSAGE);
            return;
        }
        if (dateFin.isBefore(dateDebut)) {
            JOptionPane.showMessageDialog(this, "La date de fin doit être après la date de début.",
                    "Erreur", JOptionPane.ERROR_MESSAGE);
            return;
        }

        double budget;
        try {
            budget = Double.parseDouble(jTextFieldBudget.getText().trim().replace(',', '.'));
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Le budget doit être un nombre.", "Erreur", JOptionPane.ERROR_MESSAGE);
            return;
        }

        mission.setTitre(titre);
        mission.setDescription(jTextFieldDescription.getText().trim());
        mission.setDateDebut(dateDebut);
        mission.setDateFin(dateFin);
        mission.setStatut((Statut) jComboBoxStatut.getSelectedItem());
        mission.setPriorite((Priorite) jComboBoxPriorite.getSelectedItem());
        mission.setBudget(budget);

        try {
            new MissionDAO().modifier(mission);
            modifie = true;
            JOptionPane.showMessageDialog(this, "Mission modifiée avec succès.");
            setVisible(false);
            dispose();
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Erreur lors de la modification : " + e.getMessage(),
                    "Erreur", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButtonValiderActionPerformed

    private void jButtonSupprimerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonSupprimerActionPerformed
        if (mission == null) {
            return;
        }

        String message = "Supprimer définitivement la mission « " + mission.getTitre() + " » ?";
        // TP2 : ON DELETE CASCADE supprimera aussi les affectations de la mission
        try {
            int nbAgents = new ParticipationDAO().listerParMission(mission.getId()).size();
            if (nbAgents > 0) {
                message += "\n\n" + nbAgents + " agent(s) y sont affectés : ces affectations seront aussi supprimées.";
            }
        } catch (SQLException e) {
            System.getLogger(ModifierMissionDialog.class.getName()).log(System.Logger.Level.WARNING, (String) null, e);
        }
        int choix = JOptionPane.showConfirmDialog(this, message,
                "Confirmation", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
        if (choix != JOptionPane.YES_OPTION) {
            return;
        }

        try {
            if (!new MissionDAO().supprimer(mission)) {
                JOptionPane.showMessageDialog(this, "Aucune mission supprimée (elle n'existe peut-être plus).",
                        "Erreur", JOptionPane.ERROR_MESSAGE);
                return;
            }
            modifie = true;   // pour que la table de ConsulterMission se recharge
            JOptionPane.showMessageDialog(this, "Mission supprimée.");
            setVisible(false);
            dispose();
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Erreur lors de la suppression : " + e.getMessage(),
                    "Erreur", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButtonSupprimerActionPerformed

