    private void initTable() {
        String[] colonnes = {
            "ID", "Titre", "Description", "Date de debut", "Date de fin", "Statut", "Priorite", "Budget", "Agents"
        }; 
        DefaultTableModel modele = new DefaultTableModel (colonnes, 0);
        MissionDAO dao = new MissionDAO(); 
        missions = new ArrayList<>();
        
        try {
            missions = dao.lister();
            // TP2 : nombre d'agents affectés à chaque mission (LEFT JOIN + COUNT)
            Map<Integer, Integer> nbAgents = new ParticipationDAO().compterAgentsParMission();
            for (Mission m : missions) {
                Object[] ligne = {
                    m.getId(),
                    m.getTitre(),
                    m.getDescription(),
                    m.getDateDebut(),
                    m.getDateFin(),
                    m.getStatut(),
                    m.getPriorite(),
                    m.getBudget(),
                    nbAgents.getOrDefault(m.getId(), 0),
                };
                modele.addRow(ligne); 
            }
        } catch (SQLException ex) {
            missions = new ArrayList<>();
            modele.setRowCount(0);
            System.getLogger(ConsulterMission.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
            MessageErreur.afficher(this, "Chargement des missions", ex);
        }
            jTableMission.setModel(modele);
            jTableMission.setDefaultEditor(Object.class, null);
            jTableMission.setAutoCreateRowSorter(true);
    }

    private void ouvrirMissionSelectionnee() {
        int ligneVue = jTableMission.getSelectedRow();
        if (ligneVue == -1) {
            return;
        }
        // Le tri est activé : on convertit l'index affiché en index du modèle
        int ligneModele = jTableMission.convertRowIndexToModel(ligneVue);
        Mission mission = missions.get(ligneModele);

        ModifierMissionDialog uneFenetre = new ModifierMissionDialog(this, true, mission);
        uneFenetre.setVisible(true); // bloquant car modal

        // Une fois la fenêtre fermée, on recharge la table si la mission a changé
        if (uneFenetre.isModifie()) {
            initTable();
        }
    }

    /**
     * TP2 : ouvre la fenêtre modale listant les agents affectés
     * à la mission sélectionnée (requête avec jointures).
     */
    private void voirAgentsMissionSelectionnee() {
        int ligneVue = jTableMission.getSelectedRow();
        if (ligneVue == -1) {
            JOptionPane.showMessageDialog(this, "Sélectionnez d'abord une mission dans le tableau.",
                    "Information", JOptionPane.INFORMATION_MESSAGE);
            return;
        }
        Mission mission = missions.get(jTableMission.convertRowIndexToModel(ligneVue));
        new ParticipationsDialog(this, mission).setVisible(true);
    }
