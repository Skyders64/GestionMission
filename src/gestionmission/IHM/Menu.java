    /**
     * Branche les boutons du menu.
     * (Fait ici plutôt que dans le designer : ça marche pareil et le mode Design reste éditable.)
     */
    private void initBoutons() {
        jButton1.addActionListener(e -> ouvrir(new AjouterMission()));
        jButton2.addActionListener(e -> ouvrir(new ConsulterMission()));
        jButton3.addActionListener(e -> ouvrir(new ModifierMission()));
        // TP2 : gestion des agents et des affectations
        jButton5.addActionListener(e -> ouvrir(new GestionAgents()));
        jButton6.addActionListener(e -> ouvrir(new GestionAffectations()));
        jButton4.addActionListener(e -> System.exit(0));
    }

    /**
     * Ouvre une fenêtre par-dessus le menu.
     * DISPOSE_ON_CLOSE : fermer cette fenêtre ne ferme plus toute l'application.
     * Le menu se cache, puis réapparaît dès que la fenêtre est fermée
     * (bouton Annuler / Retour, ou la croix).
     */
    private void ouvrir(javax.swing.JFrame fenetre) {
        fenetre.setDefaultCloseOperation(javax.swing.WindowConstants.DISPOSE_ON_CLOSE);
        fenetre.addWindowListener(new java.awt.event.WindowAdapter() {
            @Override
            public void windowClosed(java.awt.event.WindowEvent e) {
                setVisible(true);
                toFront();
            }
        });
        fenetre.setLocationRelativeTo(this);
        setVisible(false);
        fenetre.setVisible(true);
    }

