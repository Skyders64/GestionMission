    private void jButtonValiderActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonValiderActionPerformed
        String titre = jTextFieldTitre.getText().trim();
        if (titre.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Le titre est obligatoire.", "Erreur", JOptionPane.ERROR_MESSAGE);
            return;
        }

        LocalDate dateDebut;
        LocalDate dateFin;
        try {
            dateDebut = LocalDate.parse(jTextFieldTitre3.getText().trim());
            dateFin = LocalDate.parse(jTextFieldTitre4.getText().trim());
        } catch (DateTimeParseException e) {
            JOptionPane.showMessageDialog(this, "Les dates doivent être au format AAAA-MM-JJ (ex : 2026-10-12).",
                    "Erreur", JOptionPane.ERROR_MESSAGE);
            return;
        }
        if (dateFin.isBefore(dateDebut)) {
            JOptionPane.showMessageDialog(this, "La date de fin doit être après la date de début.",
                    "Erreur", JOptionPane.ERROR_MESSAGE);
            return;
        }

        double budget;
        try {
            budget = Double.parseDouble(jTextFieldTitre5.getText().trim().replace(',', '.'));
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Le budget doit être un nombre.", "Erreur", JOptionPane.ERROR_MESSAGE);
            return;
        }

        Mission m = new Mission();
        m.setTitre(titre);
        m.setDescription(jTextFieldTitre1.getText().trim());
        m.setDateDebut(dateDebut);
        m.setDateFin(dateFin);
        m.setStatut((Statut) jComboBox2.getSelectedItem());
        m.setPriorite((Priorite) jComboBox1.getSelectedItem());
        m.setBudget(budget);

        try {
            new MissionDAO().ajouter(m);
            JOptionPane.showMessageDialog(this, "Mission ajoutée avec succès.");
            viderChamps();
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Erreur lors de l'ajout : " + e.getMessage(),
                    "Erreur", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButtonValiderActionPerformed

